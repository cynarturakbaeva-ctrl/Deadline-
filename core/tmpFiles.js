'use strict';

// МАҢЫЗДЫ: index.js (HTML) және pptxExporter.js (PPTX) бұрын шығыс файл
// атауын тек `Date.now()`-мен құратын (`presentation-${Date.now()}.html`).
// Бот бір мезгілде БІРНЕШЕ пайдаланушыға қызмет көрсетеді (processing Set
// чат бойынша бөлек, жаһандық емес) — егер екі ӘРТҮРЛІ чат дәл сол
// миллисекундта осы қадамға жетсе (сирек, бірақ мүмкін: LLM+Puppeteer
// уақыты айнымалы болғандықтан толық синхрондалу ықтималдығы жоқ емес),
// екі процесс БІРДЕЙ файл жолын қолданып, бірінің шығысын екіншісі
// үстінен жазып кетуі мүмкін еді (Puppeteer әлі оқып жатқан HTML файлды
// немесе жазылып жатқан PPTX-ті). Бұл функция pid + монотонды санауыш +
// кездейсоқ жолды қосып, бір процесс ішінде де, бірнеше процесс арасында
// да соқтығыспауды кепілдендіреді.
let counter = 0;

function uniqueId() {
  counter = (counter + 1) % 1e6;
  const rand = Math.random().toString(36).slice(2, 8);
  return `${Date.now()}-${process.pid}-${counter}-${rand}`;
}

module.exports = { uniqueId };
